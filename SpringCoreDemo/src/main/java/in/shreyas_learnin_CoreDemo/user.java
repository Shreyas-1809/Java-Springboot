package in.shreyas_learnin_CoreDemo;

public class user {
    private string name;

    public string getName() {
        return name;
    }

    public void setName(string name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public user(string name, int age) {
        this.name = name;
        this.age = age;
    }

    private int age;

}
